// rotation_table[start][destination]
const table_entry rotation_table[4][4] = {
    //               to BLACK,to ALUMINIUM,to WHITE,to STEEL
    /* BLACK     */ {{0, CW}, {50, CW}, {100, CW}, {50, CCW}},
    /* ALUMINIUM */ {{50, CCW}, {0, CW}, {50, CW}, {100, CW}},
    /* WHITE     */ {{100, CW}, {50, CCW}, {0, CW}, {50, CW}},
    /* STEEL     */ {{50, CW}, {100, CW}, {50, CCW}, {0, CW}},
};

uint8_t stepper_state_step(uint8_t current_step, uint8_t dir)
{
    uint8_t next_step = 0;
    switch (current_step)
    {
    case 1:
        if (dir == CW)
        {
            next_step = 2;
        }
        else
        {
            next_step = 4;
        }
        break;
    case 2:
        if (dir == CW)
        {
            next_step = 3;
        }
        else
        {
            next_step = 1;
        }
        break;
    case 3:
        if (dir == CW)
        {
            next_step = 4;
        }
        else
        {
            next_step = 2;
        }
        break;
    case 4:
        if (dir == CW)
        {
            next_step = 1;
        }
        else
        {
            next_step = 3;
        }
        break;
    default:
        break;
    } // switch
    return next_step;
}

uint8_t rotate(uint8_t dir, uint8_t steps, uint8_t current_step)
{
    while (steps > 0)
    {
        PORTA = portA_table[current_step - 1];
        current_step = stepper_state_step(current_step, dir);
        steps--;
        mTimer(15);
    } // while
    return current_step;
} // rotate

uint8_t s_curve_50(uint8_t dir, uint8_t current_step)
{
    for (uint8_t i = 0; i < 50; i++)
    {
        current_step = stepper_state_step(current_step, dir);
        PORTA = portA_table[current_step - 1];
        uTimer(scurve_50_us[i]);
    }
    return current_step;
}

uint8_t s_curve_100(uint8_t dir, uint8_t current_step)
{
    for (uint8_t i = 0; i < 100; i++)
    {
        current_step = stepper_state_step(current_step, dir);
        PORTA = portA_table[current_step - 1];
        uTimer(scurve_100_us[i]);
    }
    return current_step;
}

int8_t home_on_black(void)
{
    while ((PINF & HE) != 0)
    {
        stepper_step = rotate(CW, 1, stepper_step);
    }
    current_region = BLACK;
    return 0;
}